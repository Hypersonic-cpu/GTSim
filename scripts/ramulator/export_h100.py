#!/usr/bin/env python3
"""Export H100 HBM3 timing from the checked-out Ramulator DSL, without bindings.

The 6400Mbps JEDEC preset is conservatively downclocked to the published H100
SXM 3.35TB/s aggregate pin bandwidth. Preserve its non-refresh CK minima;
recompute refresh periods from their specified ns values, not workload errors.
"""
import argparse
import json
import math
import sys
from pathlib import Path


def main():
    root = Path(__file__).resolve().parents[2]
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path, default=root / 'configs/ramulator/h100_hbm3.yaml')
    args = parser.parse_args()
    sys.path.insert(0, str(root / '3rdparty/ramulator2/python'))
    import ramulator

    hbm3 = ramulator.dram.HBM3
    # HBM3 moves four bits per DQ per CK. Round UP to an even ps period,
    # because this revision exports half-CK ticks as integer picoseconds.
    ck_ps = 2 * math.ceil((4 * 5120 * 1000 / (8 * 3350)) / 2)
    org = hbm3.org_presets['HBM3_16Gb_8hi']
    refresh = dict(
        nRFC=hbm3._resolve_nRFC(org['density'] / org['sid'], ck_ps),
        nREFI=hbm3._resolve_nREFI(ck_ps),
        nREFIpb=hbm3._resolve_nREFIpb(ck_ps, org['bank'], org['bankgroup'], org['sid']),
        nRREFD=hbm3._resolve_nRREFD(ck_ps),
    )
    refresh['nRFMab'] = refresh['nRFC']
    dram = hbm3(org_preset='HBM3_16Gb_8hi', timing_preset='HBM3_6400Mbps',
                tCK_ps=ck_ps, rate=round(4_000_000 / ck_ps), **refresh)
    controller = ramulator.controller.HBM34(
        dram=dram, read_buffer_size=32, write_buffer_size=32,
        scheduler=ramulator.scheduler.FRFCFS(),
        refresh_manager=ramulator.refresh_manager.HBM34PerBankRefresh(),
        row_policy=ramulator.row_policy.Open(),
        addr_mapper=ramulator.addr_mapper.PassThroughAddrMapper(),
    )
    config = dict(
        frontend=ramulator.frontend.External(clock_ratio=1).to_config(),
        memory_system=ramulator.memory_system.GenericDRAM(
            clock_ratio=1, controllers=[controller] * 80,
            channel_mapper=ramulator.channel_mapper.PassThroughChannelMapper(),
        ).to_config(),
    )
    # YAML aliases retain the unmodified Ramulator config structure while
    # keeping the shared channel timing template compact and reviewable.
    memory = config['memory_system']
    template = json.dumps(memory['controllers'][0], separators=(',', ':'))
    lines = [
        '# Generated by scripts/ramulator/export_h100.py from the registered Ramulator DSL.',
        '# Derived timing data is covered by 3rdparty/ramulator2/LICENSE (MIT).',
        '# Full CK: 766ps; half-CK tick: 383ps; pin bandwidth: 3342.037 GB/s.',
        'frontend: ' + json.dumps(config['frontend']),
        'memory_system:',
        '  impl: GenericDRAM',
        '  clock_ratio: 1',
        '  channel_mapper: {impl: PassThroughChannelMapper}',
        '  controllers:',
        '    - &hbm3_channel ' + template,
        *['    - *hbm3_channel'] * 79,
    ]
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text('\n'.join(lines) + '\n')
    print(f'{args.output}: CK={ck_ps}ps, tick={ck_ps//2}ps, '
          f'pin bandwidth={4*5120*1000/(8*ck_ps):.3f}GB/s')


if __name__ == '__main__':
    main()
